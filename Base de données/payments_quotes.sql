-- ---------------------------------------------------------------------------
-- Transitions de statut : ADMIN uniquement (RPC). Pas d'UPDATE libre frontend.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.admin_set_payment_status(
  p_payment_id bigint,
  p_new_status text
)
RETURNS public.payments
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_payment public.payments;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF p_new_status NOT IN ('PAID', 'FAILED', 'REFUNDED') THEN
    RAISE EXCEPTION 'invalid status';
  END IF;

  SELECT * INTO v_payment
  FROM public.payments
  WHERE id = p_payment_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'payment not found';
  END IF;

  IF NOT (
    (v_payment.status = 'PENDING' AND p_new_status IN ('PAID', 'FAILED'))
    OR (v_payment.status = 'PAID' AND p_new_status = 'REFUNDED')
  ) THEN
    RAISE EXCEPTION 'transition not allowed';
  END IF;

  UPDATE public.payments
  SET status = p_new_status
  WHERE id = p_payment_id
    AND status = v_payment.status
  RETURNING * INTO v_payment;

  RETURN v_payment;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_set_payment_status(bigint, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_set_payment_status(bigint, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- AFTER UPDATE : notifications + commissions uniquement.
-- Ne protège PAS les champs ni les transitions (déjà gérés par
-- trg_protect_payment_row / protect_payment_row).
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.payments_notify_and_commission()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_rate numeric(8,4);
  v_commission numeric(12,2);
  v_artisan numeric(12,2);
BEGIN
  IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RETURN NEW;
  END IF;

  IF OLD.status = 'PENDING' AND NEW.status = 'PAID' THEN
    PERFORM public.notify_account(
      NEW.client_id,
      'Paiement confirmé',
      'Votre paiement a été confirmé.'
    );
    PERFORM public.notify_account(
      NEW.artisan_id,
      'Paiement confirmé',
      'Un paiement a été confirmé pour une de vos interventions.'
    );

    SELECT numeric_value INTO v_rate
    FROM public.platform_settings
    WHERE key = 'commission_rate';

    IF v_rate IS NOT NULL AND v_rate >= 0 AND v_rate < 1 THEN
      v_commission := round(NEW.amount * v_rate, 2);
      v_artisan := round(NEW.amount - v_commission, 2);

      INSERT INTO public.platform_commissions (
        payment_id, booking_id, artisan_id, gross_amount,
        commission_rate, commission_amount, artisan_amount, currency
      )
      VALUES (
        NEW.id, NEW.booking_id, NEW.artisan_id, NEW.amount,
        v_rate, v_commission, v_artisan, COALESCE(NEW.currency, 'XOF')
      )
      ON CONFLICT (payment_id) DO NOTHING;
    END IF;
  ELSIF OLD.status = 'PENDING' AND NEW.status = 'FAILED' THEN
    PERFORM public.notify_account(
      NEW.client_id,
      'Paiement échoué',
      'Le paiement n''a pas pu être confirmé.'
    );
  ELSIF OLD.status = 'PAID' AND NEW.status = 'REFUNDED' THEN
    PERFORM public.notify_account(
      NEW.client_id,
      'Remboursement',
      'Un remboursement a été enregistré.'
    );
    PERFORM public.notify_account(
      NEW.artisan_id,
      'Remboursement',
      'Un remboursement a été enregistré pour une intervention.'
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_payments_quotes_guard ON public.payments;
DROP TRIGGER IF EXISTS trg_payments_notify_and_commission ON public.payments;

CREATE TRIGGER trg_payments_notify_and_commission
AFTER UPDATE ON public.payments
FOR EACH ROW
EXECUTE FUNCTION public.payments_notify_and_commission();

GRANT SELECT ON public.booking_quotes TO authenticated;
