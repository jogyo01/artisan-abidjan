CREATE OR REPLACE FUNCTION public.admin_set_commission_rate(p_rate numeric)
RETURNS numeric
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF p_rate IS NULL OR p_rate < 0 OR p_rate >= 1 THEN
    RAISE EXCEPTION 'invalid commission rate';
  END IF;

  INSERT INTO public.platform_settings (key, numeric_value, updated_at)
  VALUES ('commission_rate', p_rate, now())
  ON CONFLICT (key) DO UPDATE
  SET numeric_value = EXCLUDED.numeric_value,
      updated_at = now();

  RETURN p_rate;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_set_commission_rate(numeric) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_set_commission_rate(numeric) TO authenticated;

