-- ---------------------------------------------------------------------------
-- Protection existante : conserver le trigger BEFORE UPDATE
-- On remplace uniquement le corps de protect_payment_row() pour
-- ajouter quote_id immuable. On ne DROP PAS trg_protect_payment_row.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.protect_payment_row()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.booking_id IS DISTINCT FROM OLD.booking_id
    OR NEW.client_id IS DISTINCT FROM OLD.client_id
    OR NEW.artisan_id IS DISTINCT FROM OLD.artisan_id
    OR NEW.amount IS DISTINCT FROM OLD.amount
    OR NEW.currency IS DISTINCT FROM OLD.currency
    OR NEW.transaction_reference IS DISTINCT FROM OLD.transaction_reference
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.payment_method IS DISTINCT FROM OLD.payment_method
    OR NEW.quote_id IS DISTINCT FROM OLD.quote_id
  THEN
    RAISE EXCEPTION 'payment fields immutable';
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NOT public.is_admin() THEN
      RAISE EXCEPTION 'payment status change not allowed';
    END IF;

    IF NOT (
      (OLD.status = 'PENDING' AND NEW.status IN ('PAID', 'FAILED'))
      OR (OLD.status = 'PAID' AND NEW.status = 'REFUNDED')
    ) THEN
      RAISE EXCEPTION 'transition not allowed';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

