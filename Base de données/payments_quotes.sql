-- ---------------------------------------------------------------------------
-- RPC artisan : créer un devis
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.artisan_create_booking_quote(
  p_booking_id bigint,
  p_amount numeric,
  p_description text DEFAULT NULL
)
RETURNS public.booking_quotes
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_role text;
  v_booking public.bookings;
  v_service public.services;
  v_quote public.booking_quotes;
BEGIN
  SELECT role INTO v_role FROM public.profiles WHERE id = auth.uid();
  IF v_role IS DISTINCT FROM 'ARTISAN' THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'invalid amount';
  END IF;

  SELECT * INTO v_booking
  FROM public.bookings
  WHERE id = p_booking_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'booking not found';
  END IF;

  IF v_booking.artisan_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF v_booking.status IS DISTINCT FROM 'ACCEPTED' THEN
    RAISE EXCEPTION 'booking not accepted';
  END IF;

  SELECT * INTO v_service
  FROM public.services
  WHERE id = v_booking.service_id;

  IF NOT FOUND OR v_service.artisan_id IS DISTINCT FROM v_booking.artisan_id THEN
    RAISE EXCEPTION 'invalid service';
  END IF;

  IF v_service.price_type NOT IN ('STARTING_FROM', 'ON_QUOTE') THEN
    RAISE EXCEPTION 'quote not required';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.payments
    WHERE booking_id = v_booking.id
      AND status IN ('PENDING', 'PAID')
  ) THEN
    RAISE EXCEPTION 'active payment exists';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.booking_quotes
    WHERE booking_id = v_booking.id
      AND status = 'ACCEPTED'
  ) THEN
    RAISE EXCEPTION 'accepted quote exists';
  END IF;

  UPDATE public.booking_quotes
  SET status = 'CANCELLED', updated_at = now()
  WHERE booking_id = v_booking.id
    AND status = 'PENDING';

  INSERT INTO public.booking_quotes (
    booking_id, artisan_id, client_id, amount, currency, status, description
  )
  VALUES (
    v_booking.id,
    v_booking.artisan_id,
    v_booking.client_id,
    round(p_amount, 2),
    'XOF',
    'PENDING',
    NULLIF(btrim(COALESCE(p_description, '')), '')
  )
  RETURNING * INTO v_quote;

  PERFORM public.notify_account(
    v_booking.client_id,
    'Devis reçu',
    'L''artisan a proposé un devis pour votre demande.'
  );

  RETURN v_quote;
END;
$$;

REVOKE ALL ON FUNCTION public.artisan_create_booking_quote(bigint, numeric, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.artisan_create_booking_quote(bigint, numeric, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- RPC client : accepter / refuser
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.client_respond_to_booking_quote(
  p_quote_id bigint,
  p_accept boolean
)
RETURNS public.booking_quotes
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_role text;
  v_quote public.booking_quotes;
  v_booking public.bookings;
  v_next text;
BEGIN
  SELECT role INTO v_role FROM public.profiles WHERE id = auth.uid();
  IF v_role IS DISTINCT FROM 'CLIENT' THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT * INTO v_quote
  FROM public.booking_quotes
  WHERE id = p_quote_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'quote not found';
  END IF;

  IF v_quote.client_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF v_quote.status IS DISTINCT FROM 'PENDING' THEN
    RAISE EXCEPTION 'quote not pending';
  END IF;

  SELECT * INTO v_booking
  FROM public.bookings
  WHERE id = v_quote.booking_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'booking not found';
  END IF;

  IF v_booking.client_id IS DISTINCT FROM v_quote.client_id
    OR v_booking.artisan_id IS DISTINCT FROM v_quote.artisan_id
  THEN
    RAISE EXCEPTION 'quote booking mismatch';
  END IF;

  IF v_booking.status IS DISTINCT FROM 'ACCEPTED' THEN
    RAISE EXCEPTION 'booking not accepted';
  END IF;

  v_next := CASE WHEN p_accept THEN 'ACCEPTED' ELSE 'REFUSED' END;

  UPDATE public.booking_quotes
  SET status = v_next, updated_at = now()
  WHERE id = v_quote.id
    AND status = 'PENDING'
  RETURNING * INTO v_quote;

  IF p_accept THEN
    PERFORM public.notify_account(
      v_quote.client_id,
      'Devis accepté',
      'Vous avez accepté le devis. Vous pouvez maintenant préparer le paiement.'
    );
    PERFORM public.notify_account(
      v_quote.artisan_id,
      'Devis accepté',
      'Le client a accepté votre devis.'
    );
  ELSE
    PERFORM public.notify_account(
      v_quote.client_id,
      'Devis refusé',
      'Vous avez refusé le devis proposé.'
    );
    PERFORM public.notify_account(
      v_quote.artisan_id,
      'Devis refusé',
      'Le client a refusé votre devis.'
    );
  END IF;

  RETURN v_quote;
END;
$$;

REVOKE ALL ON FUNCTION public.client_respond_to_booking_quote(bigint, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.client_respond_to_booking_quote(bigint, boolean) TO authenticated;

